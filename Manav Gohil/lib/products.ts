// Helper queries
export function getAllProducts(): Product[] {
  return PRODUCTS
}

export function getProductBySlug(slug: string): Product | undefined {
  return PRODUCTS.find((p) => p.slug === slug)
}

export function getProductById(id: string): Product | undefined {
  return PRODUCTS.find((p) => p.id === id)
}

export function getProductsByCollection(collectionSlug: string): Product[] {
  if (collectionSlug === 'all') return PRODUCTS
  if (collectionSlug === 'new-arrivals') return PRODUCTS.filter((p) => p.isNewArrival)
  return PRODUCTS.filter((p) => p.collection === collectionSlug)
}

export function getRelatedProducts(currentId: string, collection: string, limit = 4): Product[] {
  return PRODUCTS.filter((p) => p.collection === collection && p.id !== currentId).slice(0, limit)
}
